#!/usr/bin/env bash
#
# ============================================================================
# config.sh — waf-rule/script 共通の設定と共通関数
# ============================================================================
#
# 【用途】
#   複数のスクリプトが共通で使う設定（AWS接続先・出力先）と、
#   コマンドライン引数で設定を上書きするための共通関数を置く。
#
# 【ここに置くもの / 置かないもの】
#   置く    … 2つ以上のスクリプトが使う値、共通関数
#   置かない… 1つのスクリプトしか使わない値（そのスクリプトの先頭に書く）
#
#   例: IPSET_NAME は waf-ipset.sh しか使わないので、あちらの設定区にある。
#
# 【上書きの優先順位】
#   1. コマンドライン引数（--AWS_REGION=us-east-1 など）… 最優先
#   2. 各スクリプト先頭の設定区
#   3. このファイル
#
# 【単体では実行しない】
#   source 専用。直接実行しても何もしない。
#
# 【費用】
#   $0（設定を読むだけ）
#
# [zjk 2026-09-18 AI補助]
# ============================================================================


# ---- 実行環境の確認 --------------------------------------------------------
#
# bash 4.4 以上を要求する。
# 4.3 以前は set -u のもとで空配列を展開するとエラーになるため、
#   "${arr[@]+"${arr[@]}"}"
# という読みにくい書き方で回避する必要があった。
# 4.4 以上ならこれが不要になり、素直に "${arr[@]}" と書ける。
# 読みやすさを優先して 4.4 以上を前提とし、古い環境では明確に止める。
# （4.4 は2016年リリース。CentOS 7 や Amazon Linux 2 の bash 4.2 は対象外）
if [ "${BASH_VERSINFO[0]}" -lt 4 ] ||
   { [ "${BASH_VERSINFO[0]}" -eq 4 ] && [ "${BASH_VERSINFO[1]}" -lt 4 ]; }; then
    echo "エラー: bash 4.4 以上が必要です（現在: ${BASH_VERSION}）" >&2
    echo "  対処: 新しい bash を入れるか、bash4.4以上の環境で実行してください。" >&2
    exit 1
fi


# ---- 共通の設定（改这里）----------------------------------------------------

# 使用する AWS プロファイル名。
#
# 【EC2 / ECS 上で動かす場合は、空のままにする（推奨）】
#   インスタンス（またはタスク）に付与した IAM ロールの権限が自動的に使われる。
#   サーバ上にアクセスキーを保存しなくて済むため、こちらが安全。
#   キーの漏洩リスクが無く、有効期限の更新も AWS 側が自動で行う。
#   権限を変えたいときも、サーバに入らず AWS 側でロールを直すだけでよい。
#
# 【EC2 以外（自社サーバ等）で動かす場合のみ、プロファイル名を書く】
#   ~/.aws/credentials の [xxx] の xxx 部分。
#   この場合はサーバ上に長期のアクセスキーを置くことになる。
#   そのキーが漏れると WAF を書き換えられるため、権限は最小限にすること
#   （必要なのは wafv2:ListIPSets / GetIPSet / UpdateIPSet の3つだけ）。
#
# 手元の端末から複数アカウントを扱い分ける場合も、ここで指定する。
AWS_PROFILE_NAME=""

# 対象リージョン。
# IPSET_SCOPE=CLOUDFRONT の場合、AWS の仕様上 us-east-1 以外では動かない。
AWS_REGION="ap-northeast-1"

# 実行記録・取得結果・送信JSONの出力先（スクリプトからの相対パス）。
# Git 追跡対象外（.gitignore 済み）。依頼元が後から復核するための証跡なので消さないこと。
LOG_DIR="analysis"

# ---- 設定ここまで ----------------------------------------------------------


# ============================================================================
# 共通関数
# ============================================================================

# func_applyConfigOverride
#   入参: $1 = 「--KEY=VALUE」形式の引数
#         $2 = 上書きを許す変数名の一覧（空白区切り）
#   出参: 終了コード 0=上書きした / 1=対象外（呼び出し側で通常の引数として扱う）
#   備考: 設定項目名をそのまま引数名にしている。
#         スクリプト先頭の設定区を見れば、指定できる名前がそのまま分かるため。
func_applyConfigOverride() {
    local kv="$1" allowed="$2"

    case "$kv" in
        --*=*) ;;
        *) return 1 ;;
    esac

    local key="${kv%%=*}"
    key="${key#--}"
    local val="${kv#*=}"

    case " $allowed " in
        *" $key "*) ;;
        *) return 1 ;;
    esac

    printf -v "$key" '%s' "$val"
    return 0
}

# func_showOverridable
#   入参: $1 = 上書きできる変数名の一覧（空白区切り）
#   出参: 使い方の説明を標準エラーに出す
func_showOverridable() {
    local name
    echo "設定の上書き（--項目名=値）:" >&2
    for name in $1; do
        echo "  --${name}=<値>" >&2
    done
}


# ============================================================================
# ログ出力（crontab で 2>&1 に落とす前提の書式）
# ============================================================================
#
# 書式: [スクリプト名] 日時 本文
#       [スクリプト名] ERROR 日時 本文
#
# crontab で複数スクリプトの出力が混ざっても、どれが出したログか分かるようにする。
# 異常だけを拾いたい場合は ERROR で grep すればよい。
#   例: 0 4 * * * /path/sync.sh >> /var/log/waf.log 2>&1
#       grep ERROR /var/log/waf.log

# ログの先頭に出すスクリプト名。起動時に1回だけ求める。
# 毎回 basename を呼ぶとプロセス生成が積み重なり、Git Bash では体感できるほど遅くなる。
SCRIPT_TAG="${SCRIPT_TAG:-${0##*/}}"

# func_info
#   入参: $* = 本文
#   出参: 標準エラーへ1行出力
#   備考: 標準出力はデータ専用のため、進捗は必ず標準エラーへ出す。
#         --pipe を付けても抑制しない。標準エラーに出す限り標準出力の純度は保たれるうえ、
#         crontab では「正常に動いた記録」が残らないと、動いていないのか
#         変更が無かったのか区別できなくなるため。
#         日時は bash 内蔵の printf で作る（date コマンドを呼ばない）。
#         Git Bash はプロセス生成が遅く、1行ごとに date を呼ぶと数秒単位で効いてくる。
func_info() {
    local now
    printf -v now '%(%Y-%m-%d %H:%M:%S)T' -1
    printf '[%s] %s %s\n' "$SCRIPT_TAG" "$now" "$*" >&2
}

# func_error
#   入参: $* = 本文
#   出参: 標準エラーへ1行出力。IS_PIPE に関係なく必ず出す
func_error() {
    local now
    printf -v now '%(%Y-%m-%d %H:%M:%S)T' -1
    printf '[%s] ERROR %s %s\n' "$SCRIPT_TAG" "$now" "$*" >&2
}

# func_errorDetail
#   入参: $1 = 見出し, $2 = 詳細が入ったファイルのパス
#   出参: ファイルに中身があれば、字下げして標準エラーへ出す
#   備考: aws CLI や curl が出した生のエラー文をそのまま見せるために使う。
#         握りつぶすと、crontab のログから原因が永久に分からなくなる。
func_errorDetail() {
    local title="$1" file="$2"
    [ -s "$file" ] || return 0
    func_error "$title"
    sed 's/^/    /' "$file" >&2
}
